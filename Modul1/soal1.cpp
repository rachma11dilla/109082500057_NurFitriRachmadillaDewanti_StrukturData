#include <iostream>
using namespace std;
int main() {
    float a, b;

    cout << "bilangan pertama: ";
    cin >> a;

    cout << "bilangan kedua: ";
    cin >> b;

    cout << "penjumlahan = " << a + b << endl;
    cout << "pengurangan = " << a - b << endl;
    cout << "perkalian   = " << a * b << endl;
    cout << "pembagian   = " << a / b << endl;

    return 0;
}